#!/usr/bin/env bash
# Rebuild ios/Tests/Fixtures/ml-reference.js, the JS pipeline that
# ModelInputParityTests runs in JavaScriptCore against ModelInputs.swift.
#
#   scripts/ml-reference/build.sh /path/to/insidepics/monorepo
#
# The bundle imports the monorepo's own face alignment, blur, tensor and
# histogram code, so rebuild it whenever those files change there.
set -euo pipefail
monorepo="$(cd "${1:?usage: build.sh <monorepo checkout>}" && pwd)"
here="$(cd "$(dirname "$0")" && pwd)"
out="$here/../../ios/Tests/Fixtures/ml-reference.js"
commit="$(git -C "$monorepo" rev-parse --short HEAD)"

pnpm dlx esbuild@0.25.10 "$here/entry.ts" --bundle --format=iife \
  --target=es2020 --legal-comments=none \
  --alias:@monorepo="$monorepo/packages" \
  --alias:@insidepics/shared="$monorepo/packages/shared/src" \
  --outfile="$out.tmp"
{
  echo "// Generated by scripts/ml-reference/build.sh from monorepo $commit. Do not edit."
  sed -E 's#^( *// ).*/(packages|scripts)/#\1\2/#' "$out.tmp"
} > "$out"
rm "$out.tmp"
