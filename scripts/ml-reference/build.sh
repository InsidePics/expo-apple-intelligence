#!/usr/bin/env bash
# Rebuild ios/Tests/Fixtures/ml-reference.js, the JS pipeline that
# ModelInputParityTests runs in JavaScriptCore against ModelInputs.swift.
#
#   scripts/ml-reference/build.sh /path/to/insidepics/monorepo [commit]
#
# The reference is the InsidePics monorepo's ML preprocessing as it ran in
# JS before it moved here: by default commit 9174e4036, the last one with
# the JS crop, alignment, blur and histogram paths. The files are read from
# that commit with `git archive`, so the checkout's own state does not matter.
set -euo pipefail
monorepo="$(cd "${1:?usage: build.sh <monorepo checkout> [commit]}" && pwd)"
commit="${2:-9174e4036}"
here="$(cd "$(dirname "$0")" && pwd)"
out="$here/../../ios/Tests/Fixtures/ml-reference.js"
src="$(mktemp -d)"
trap 'rm -rf "$src"' EXIT

git -C "$monorepo" archive "$commit" packages/ui/src/providers/ml packages/shared/src/utils |
  tar -x -C "$src"

pnpm dlx esbuild@0.25.10 "$here/entry.ts" --bundle --format=iife \
  --target=es2020 --legal-comments=none \
  --alias:@monorepo="$src/packages" \
  --alias:@insidepics/shared="$src/packages/shared/src" \
  --outfile="$src/out.js"
{
  echo "// Generated by scripts/ml-reference/build.sh from monorepo $commit. Do not edit."
  sed -E 's#^( *// ).*/(packages|scripts)/#\1\2/#' "$src/out.js"
} > "$out"
